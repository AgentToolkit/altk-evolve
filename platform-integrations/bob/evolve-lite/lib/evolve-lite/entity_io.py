_FRONTMATTER_KEYS = ("type", "name", "trigger", "trajectory", "owner", "source", "visibility", "published_at", "version", "atomic_skills", "product", "derived_from_failure")


# Optional markdown body sections, in serialisation order.
# Maps entity dict key -> markdown heading display name.
# Single-word keys: heading == key.capitalize().
# Multi-word keys: heading is the value (with spaces / title-case).
_BODY_SECTIONS = ("rationale", "success_rubric", "requirements", "imports", "dependencies", "documentation", "changelog")

# Heading display names for keys that don't map via simple .capitalize()
_SECTION_HEADING_OVERRIDE = {
    "success_rubric": "Success Rubric",
}

def _section_heading(key):
    """Return the markdown heading text for a body-section key."""
    return _SECTION_HEADING_OVERRIDE.get(key, key.capitalize())

def _heading_to_key(heading):
    """Reverse-map a matched heading back to the entity dict key."""
    _reverse = {v.lower(): k for k, v in _SECTION_HEADING_OVERRIDE.items()}
    return _reverse.get(heading.lower(), heading.lower())


def entity_to_markdown(entity):
    """Serialize an entity dict to markdown with YAML frontmatter.

    Args:
        entity: dict with keys ``content``, and optionally ``type``,
                ``trigger``, ``rationale``, ``requirements``, ``imports``,
                ``dependencies``, ``documentation``.

    Returns:
        A string suitable for writing to a ``.md`` file.
    """
    lines = ["---"]
    for key in _FRONTMATTER_KEYS:
        val = entity.get(key)
        if val:
            lines.append(f"{key}: {val}")
    lines.append("---")
    lines.append("")

    content = entity.get("content", "")
    lines.append(content)

    for section_key in _BODY_SECTIONS:
        val = entity.get(section_key)
        if val and val.strip():
            heading = f"## {_section_heading(section_key)}"
            lines.append("")
            lines.append(heading)
            lines.append("")
            lines.append(val.strip())

    lines.append("")
    return "\n".join(lines)


def markdown_to_entity(path):
    """Parse a markdown entity file back into a dict.

    Handles YAML frontmatter with simple ``key: value`` lines (no nested
    structures, no PyYAML dependency).

    Recognised body sections (parsed into entity dict keys):
        ## Rationale, ## Requirements, ## Imports, ## Dependencies,
        ## Documentation

    Returns:
        dict with ``content`` plus any recognised section keys.
    """
    path = Path(path)
    text = path.read_text(encoding="utf-8")

    entity = {}

    # Split frontmatter
    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) >= 3:
            frontmatter = parts[1].strip()
            body = parts[2]
            for line in frontmatter.splitlines():
                line = line.strip()
                if not line:
                    continue
                key, _, value = line.partition(":")
                key = key.strip()
                value = value.strip()
                if key and value:
                    entity[key] = value
        else:
            body = text
    else:
        body = text

    # Split body into content + known optional sections.
    # A section begins at "## <Heading>" and runs until the next "## " heading
    # or end of string.  Content is everything before the first known heading.
    body = body.strip()

    # Build a regex that matches any of the known section headings
    _known_headings = "|".join(re.escape(_section_heading(s)) for s in _BODY_SECTIONS)
    _section_re = re.compile(
        rf"^## ({_known_headings})\s*$", re.MULTILINE | re.IGNORECASE
    )

    first_match = _section_re.search(body)
    if first_match:
        content = body[: first_match.start()].strip()
    else:
        content = body

    if content:
        entity["content"] = content

    # Walk through all section matches and capture text until the next heading
    matches = list(_section_re.finditer(body))
    for i, m in enumerate(matches):
        section_name = _heading_to_key(m.group(1))
        section_start = m.end()
        section_end = matches[i + 1].start() if i + 1 < len(matches) else len(body)
        section_text = body[section_start:section_end].strip()
        if section_text:
            entity[section_name] = section_text

    return entity


def _parse_frontmatter_lines(lines):
    """Parse simple YAML-style frontmatter lines into a dict."""
    entity = {}
    for raw_line in lines:
        line = raw_line.strip()
        if not line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if key and value:
            entity[key] = value
    return entity


def _parse_frontmatter_only(path):
    """Parse only the frontmatter section from a markdown entity file."""
    path = Path(path)
    try:
        with path.open(encoding="utf-8") as handle:
            if handle.readline().strip() != "---":
                return {}

            frontmatter_lines = []
            found_closing = False
            for line in handle:
                if line.strip() == "---":
                    found_closing = True
                    break
                frontmatter_lines.append(line)
    except (OSError, UnicodeDecodeError):
        return {}

    if not found_closing:
        return {}

    return _parse_frontmatter_lines(frontmatter_lines)


def _manifest_path(path):
    """Return a manifest path relative to the project root (parent of the evolve dir).

    This keeps manifest paths stable regardless of the caller's working directory,
    so hooks invoked from a subdirectory still emit ``.evolve/entities/...`` paths.
    """
    path = Path(path)
    try:
        project_root = get_evolve_dir().resolve().parent
        return str(path.resolve().relative_to(project_root))
    except ValueError:
        return str(path)


def dedupe_manifest_entries(entries):
    """Return deterministically ordered manifest entries with exact dedupe."""
    normalized = []
    seen = set()
    for entry in sorted(entries, key=lambda item: (item["path"], item["type"], item["trigger"])):
        key = (entry["path"], entry["type"], entry["trigger"])
        if key in seen:
            continue
        seen.add(key)
        normalized.append(entry)
    return normalized


def load_manifest(root_dir):
    """Load a frontmatter-only manifest from a recall root."""
    root_dir = Path(root_dir)
    entries = []
    for md in sorted(root_dir.glob("**/*.md")):
        if md.is_symlink() or ".git" in md.parts:
            continue
        # Skip the subscribed/ subtree — those are read-only remote clones and
        # may contain stale entity versions that conflict with local entities.
        if "subscribed" in Path(md).resolve().parts:
            continue

        entity = _parse_frontmatter_only(md)
        entity_type = entity.get("type")
        trigger = entity.get("trigger")
        if not entity_type or not trigger:
            continue

        entry = {
            "path": _manifest_path(md),
            "type": entity_type,
            "trigger": trigger,
        }
        if entity.get("derived_from_failure") == "true":
            entry["derived_from_failure"] = True
        entries.append(entry)

    return dedupe_manifest_entries(entries)


