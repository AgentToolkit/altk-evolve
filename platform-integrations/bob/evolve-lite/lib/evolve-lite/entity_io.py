def write_clone_gitignore(clone_root):
    """Write a protective .gitignore into the clone root.

    Blocks common noise files (.venv, .env, .vscode, __pycache__, etc.) from
    ever being staged or pushed from a publish clone.  Safe to call multiple
    times — overwrites only when the file does not yet exist or was written by
    a previous evolve-lite version (detected by the auto-generated header).

    Args:
        clone_root: Path to the root of the local git clone.
    """
    clone_root = Path(clone_root)
    target = clone_root / ".gitignore"

    if target.exists():
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError:
            return
        # Only overwrite if this is our own auto-generated file.
        if "Auto-generated by evolve-lite" not in existing:
            return

    try:
        fd, tmp_path = tempfile.mkstemp(dir=clone_root, prefix=".gitignore.", suffix=".tmp")
        try:
            os.write(fd, _CLONE_GITIGNORE_CONTENT.encode("utf-8"))
            os.close(fd)
            fd = None
            os.replace(tmp_path, str(target))
        finally:
            if fd is not None:
                os.close(fd)
            if os.path.exists(tmp_path):
                os.unlink(tmp_path)
    except OSError:
        pass


