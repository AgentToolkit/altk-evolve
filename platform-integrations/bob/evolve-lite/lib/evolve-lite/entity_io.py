# Default registry lives next to this file.
_PRODUCTS_CONFIG = Path(__file__).with_name("products.yaml")


def _parse_products_yaml(text):
    """Minimal YAML parser for the products.yaml format.

    Handles only the subset used by products.yaml:
      products:
        - slug: foo
          patterns:
            - pattern1
            - pattern2

    No PyYAML dependency required.
    """
    entries = []
    current = None
    in_patterns = False

    for raw in text.splitlines():
        line = raw.rstrip()
        stripped = line.lstrip()

        if stripped.startswith("- slug:"):
            if current:
                entries.append(current)
            current = {"slug": stripped[len("- slug:"):].strip(), "patterns": []}
            in_patterns = False

        elif stripped == "patterns:" and current is not None:
            in_patterns = True

        elif in_patterns and stripped.startswith("- ") and current is not None:
            current["patterns"].append(stripped[2:].strip())

        elif stripped and not stripped.startswith("#") and not stripped.startswith("-"):
            in_patterns = False

    if current:
        entries.append(current)
    return entries


def load_product_registry(entities_dir=None):
    """Return the merged product registry.

    Combines two sources in priority order:

    1. **Config file** (``.bob/lib/evolve-lite/products.yaml`` or the file
       adjacent to this module): declared products with explicit match patterns.
    2. **Existing entity folders**: any ``{type}/{product}/`` subdirectories
       under *entities_dir* that are not already in the config are added as
       folder-only products (matched by slug-token heuristic; no explicit
       patterns).

    Returns:
        list[dict]: each dict has ``"slug"`` (str) and ``"patterns"``
        (list[str], may be empty for folder-only entries).
    """
    # 1. Load from config file
    config_entries = []
    config_slugs = set()
    if _PRODUCTS_CONFIG.is_file():
        try:
            config_entries = _parse_products_yaml(
                _PRODUCTS_CONFIG.read_text(encoding="utf-8")
            )
            config_slugs = {e["slug"] for e in config_entries}
        except OSError:
            pass

    # 2. Discover folder-only products not already in config
    if entities_dir is None:
        entities_dir = get_evolve_dir() / "entities"
    entities_dir = Path(entities_dir)

    folder_slugs = set()
    if entities_dir.is_dir():
        for type_dir in entities_dir.iterdir():
            if not type_dir.is_dir() or type_dir.name.startswith("."):
                continue
            for product_dir in type_dir.iterdir():
                if (
                    product_dir.is_dir()
                    and product_dir.name != "general"
                    and product_dir.name not in config_slugs
                ):
                    folder_slugs.add(product_dir.name)

    # Merge: config entries first, then folder-only entries (no patterns)
    registry = list(config_entries)
    for slug in sorted(folder_slugs):
        registry.append({"slug": slug, "patterns": []})

    return registry


