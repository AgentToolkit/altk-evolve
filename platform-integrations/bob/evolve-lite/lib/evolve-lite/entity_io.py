def get_evolve_dir():
    """Return the .evolve root directory.

    Uses ``EVOLVE_DIR`` env var if set, otherwise ``.evolve/`` in cwd.
    Does not create the directory.
    """
    env_dir = os.environ.get("EVOLVE_DIR")
    if env_dir:
        return Path(env_dir)
    return Path(".evolve")


def find_entities_dir():
    """Locate the entities directory.

    Uses :func:`get_evolve_dir` to determine the base directory, then
    returns the ``entities/`` subdirectory Path if it exists, else ``None``.
    """
    c = get_evolve_dir() / "entities"
    return c if c.is_dir() else None


def find_recall_entity_dirs():
    """Locate all directories that should be searched during recall.

    Returns the existing recall roots. Only private entities contribute to
    recall: ``entities/`` (private entities) and ``public/`` (entities
    published by the local project). Subscribed clones under
    ``entities/subscribed/`` are excluded.
    """
    evolve_dir = get_evolve_dir()
    entities_dir = evolve_dir / "entities"
    public_dir = evolve_dir / "public"
    candidates = [entities_dir, public_dir]
    return [path for path in candidates if path.is_dir()]


def get_default_entities_dir():
    """Return (and create) the default entities directory.

    Uses ``EVOLVE_DIR`` if set, falls back to ``.evolve/entities/``.
    """
    base = get_evolve_dir() / "entities"
    base.mkdir(parents=True, exist_ok=True)
    return base.resolve()


# ---------------------------------------------------------------------------
# Banality check (shared by save_entities.py and refine.py)
# ---------------------------------------------------------------------------

# Universally-known single-step practices that add no recall value
_BANAL_PATTERNS = [
    # Generic Python env / packaging
    r"^activate\s+(the\s+)?virtual\s+(environment|env)\s*\.?\s*$",
    r"^install\s+dependencies\s*\.?\s*$",
    r"^run\s+(the\s+)?(application|app|script|program)\s*\.?\s*$",
    r"^set\s+up\s+(a\s+)?virtual\s+(environment|env)\s*\.?\s*$",
    r"^create\s+a\s+requirements\.txt\s*\.?\s*$",
    r"^import\s+(a\s+)?module\s*\.?\s*$",
    # Basic file ops
    r"^(create|write|make)\s+a\s+(file|directory|folder)\s*\.?\s*$",
    r"^read\s+(a\s+)?file\s*\.?\s*$",
    r"^write\s+to\s+(a\s+)?file\s*\.?\s*$",
    r"^delete\s+(a\s+)?file\s*\.?\s*$",
    # Basic git
    r"^git\s+(add|commit|push|pull|status|log)\s*\.?\s*$",
    r"^create\s+a\s+(git\s+)?branch\s*\.?\s*$",
    # Fatally vague
    r"^when\s+performing\s+",
    r"^do\s+something\s*\.?\s*$",
    r"^use\s+(the\s+)?\w+\s*\.?\s*$",
]

_BANAL_RE = [re.compile(p, re.IGNORECASE) for p in _BANAL_PATTERNS]


def check_banality(entity):
    """Return ``(is_banal, reason)`` for *entity*.

    An entity is banal when it would provide no recall value because:

    1. **Empty / trivially short** — content ≤ 30 chars with no backtick command.
    2. **Common-sense pattern** — content or trigger matches a curated list of
       universally-known single-step practices.
    3. **Pure trigger restatement** — content body is a near-verbatim copy of the
       trigger, adding nothing (Jaccard ≥ 0.85 between the two).
    4. **Slug tautology** — content or trigger consists only of tokens already
       present in the filename slug, meaning the entity says nothing that isn't
       already encoded in its own name.

    Returns:
        tuple[bool, str]: ``(True, reason_string)`` if banal, else ``(False, "")``.
    """
    content = entity.get("content", "").strip()
    trigger = entity.get("trigger", "").strip()

    # 1. Too short and no command
    if len(content) <= 30 and not re.search(r"`[^`]+`", content):
        return True, f"content too short ({len(content)} chars) and contains no command"

    combined = f"{content} {trigger}".lower()

    # 2. Common-sense pattern match
    for pat in _BANAL_RE:
        if pat.search(content.lower()) or pat.search(trigger.lower()):
            return True, f"matches common-sense pattern: '{pat.pattern}'"

    # 3. Trigger restatement — content is essentially the trigger re-worded
    def _tok(t):
        words = re.findall(r"[a-z0-9]+", t.lower())
        _stop = {"the", "a", "an", "and", "or", "in", "on", "at", "to", "for",
                 "of", "with", "by", "from", "as", "is", "was", "are", "be",
                 "when", "after", "while", "if", "how", "this", "that"}
        return {w for w in words if w not in _stop and len(w) > 2}

    c_tok = _tok(content)
    t_tok = _tok(trigger)
    if c_tok and t_tok:
        inter = len(c_tok & t_tok)
        union = len(c_tok | t_tok)
        jac = inter / union
        if jac >= 0.85:
            return True, f"content is a near-verbatim restatement of trigger (Jaccard={jac:.2f})"

    return False, ""


# ---------------------------------------------------------------------------
# Slugify / filename helpers
# ---------------------------------------------------------------------------


def slugify(text, max_length=60, product=None):
    """Convert *text* to a filesystem-safe slug with optional product prefix.

    >>> slugify("Use temp files for JSON transfer!")
    'use-temp-files-for-json-transfer'
    >>> slugify("Activate environment", product="watson-orchestrate")
    'watson-orchestrate-activate-environment'
    """
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    text = text.strip("-")
    
    # Add product prefix if provided
    if product:
        product_slug = re.sub(r"[^a-z0-9]+", "-", product.lower()).strip("-")
        text = f"{product_slug}-{text}"
    
    # Truncate at max_length, but don't break in the middle of a word
    if len(text) > max_length:
        text = text[:max_length].rsplit("-", 1)[0]
    return text or "entity"


def unique_filename(directory, slug):
    """Return a Path that doesn't collide with existing files in *directory*.

    Tries ``slug.md``, then ``slug-2.md``, ``slug-3.md``, etc.
    """
    directory = Path(directory)
    candidate = directory / f"{slug}.md"
    if not candidate.exists():
        return candidate
    n = 2
    while True:
        candidate = directory / f"{slug}-{n}.md"
        if not candidate.exists():
            return candidate
        n += 1


